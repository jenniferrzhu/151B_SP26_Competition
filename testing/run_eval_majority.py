"""Re-score the multishot run using majority vote instead of the LLM selector.

Reuses candidates already generated by run_eval.py (Multishot v1) — no GPU needed.
For each prompt: extract boxed answer from each candidate, normalize via the
judger, and pick the most common. Tie-broken by candidate order (first wins).

Outputs:
  results/Multishot v1 (majority)/predictions.jsonl
  results/Multishot v1 (majority)/accuracy.txt
"""
import json
import os
import re
import sys
from collections import Counter
from pathlib import Path

SRC_PRED   = "results/Multishot v1/predictions.jsonl"
TEST_NAME  = "Multishot v1 (majority equiv)"
PRED_PATH  = f"results/{TEST_NAME}/predictions.jsonl"
ACC_PATH   = f"results/{TEST_NAME}/accuracy.txt"


def extract_letter(text: str) -> str:
    think_end = text.rfind("</think>")
    search_text = text[think_end + len("</think>"):] if think_end >= 0 else text
    m = re.search(r"\\boxed\{\s*([A-Za-z])\s*\}", search_text)
    if not m:
        m = re.search(r"\\boxed\{\s*([A-Za-z])\s*\}", text)
    if m:
        return m.group(1).upper()
    matches = re.findall(r"\b([A-Z])\b", search_text.upper())
    if not matches:
        matches = re.findall(r"\b([A-Z])\b", text.upper())
    return matches[-1] if matches else ""


def main() -> None:
    Path(PRED_PATH).parent.mkdir(parents=True, exist_ok=True)
    sys.path.insert(0, ".")
    from judger import Judger
    judger = Judger(strict_extract=False)

    src = [json.loads(line) for line in open(SRC_PRED)]
    print(f"Loaded {len(src)} records from {SRC_PRED}")

    results = []
    for rec in src:
        is_mcq = rec["is_mcq"]
        gold = rec["gold"]
        candidates = rec["candidates"]

        # extract+normalize each candidate's answer
        votes = []
        for cand in candidates:
            if is_mcq:
                vote = extract_letter(cand)
            else:
                # use judger's extract_ans for free-form
                ans = judger.extract_ans(cand)
                # normalize each comma-separated piece, then join
                if ans:
                    parts = judger.split_by_comma(ans)
                    norm_parts = [judger.norm_ans_str(p) for p in parts]
                    vote = ", ".join(norm_parts) if norm_parts else ""
                else:
                    vote = ""
            votes.append(vote)

        # Cluster votes by mathematical equivalence via the judger.
        # For MCQ we already have canonical letters → exact string equality is fine.
        # For free-form we use judger.is_equal so 80.7 and 80.6551724... cluster together.
        non_empty = [v for v in votes if v]
        if not non_empty:
            chosen, freq = "", 0
        elif is_mcq:
            counter = Counter(non_empty)
            chosen, freq = counter.most_common(1)[0]
        else:
            clusters = []  # list of [representative, count]
            for v in non_empty:
                placed = False
                for c in clusters:
                    try:
                        if judger.is_equal(v, c[0]):
                            c[1] += 1
                            placed = True
                            break
                    except Exception:
                        pass
                if not placed:
                    clusters.append([v, 1])
            # pick largest cluster (ties → first encountered, i.e. earliest candidate)
            clusters.sort(key=lambda c: -c[1])
            chosen, freq = clusters[0]

        # score the chosen answer against gold
        if is_mcq:
            correct = (chosen == str(gold).strip().upper())
            response = f"\\boxed{{{chosen}}}" if chosen else ""
        else:
            response = f"\\boxed{{{chosen}}}" if chosen else ""
            gold_list = gold if isinstance(gold, list) else [gold]
            try:
                correct = judger.auto_judge(
                    pred=response, gold=gold_list, options=[[]] * len(gold_list),
                )
            except Exception:
                correct = False

        results.append({
            "id": rec["id"],
            "is_mcq": is_mcq,
            "gold": gold,
            "votes": votes,
            "chosen": chosen,
            "vote_freq": freq,
            "response": response,
            "correct": correct,
        })

    with open(PRED_PATH, "w") as f:
        for r in results:
            f.write(json.dumps(r) + "\n")

    mcq_res = [r for r in results if r["is_mcq"]]
    free_res = [r for r in results if not r["is_mcq"]]

    def acc(subset):
        return sum(r["correct"] for r in subset) / len(subset) * 100 if subset else 0.0

    summary = (
        f"Majority-vote scoring of multishot candidates (no LLM selector)\n"
        f"Source: {SRC_PRED}\n"
        f"Test set size: {len(results)}\n"
        f"\n"
        f"  MCQ        : {sum(r['correct'] for r in mcq_res):4d} / {len(mcq_res):4d}  ({acc(mcq_res):.2f}%)\n"
        f"  Free-form  : {sum(r['correct'] for r in free_res):4d} / {len(free_res):4d}  ({acc(free_res):.2f}%)\n"
        f"  Overall    : {sum(r['correct'] for r in results):4d} / {len(results):4d}  ({acc(results):.2f}%)\n"
    )
    print(summary)
    with open(ACC_PATH, "w") as f:
        f.write(summary)
    print(f"Saved predictions to {PRED_PATH}")
    print(f"Saved accuracy to {ACC_PATH}")


if __name__ == "__main__":
    main()
